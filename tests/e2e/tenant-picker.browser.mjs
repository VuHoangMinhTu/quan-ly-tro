import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = fileURLToPath(new URL('../../', import.meta.url))
const require = createRequire(resolve(root, 'front-end/package.json'))
const { createServer } = await import(pathToFileURL(require.resolve('vite')))
const { chromium } = createRequire(process.env.PLAYWRIGHT_PACKAGE_PATH || 'C:/Users/Yato/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/package.json')('playwright')
const origin = 'http://127.0.0.1:18948'
const output = resolve(root, 'tmp/tenant-picker')
const tenants = Array.from({ length: 45 }, (_, i) => ({ id: i + 1, full_name: `Người thử ${String(i + 1).padStart(2, '0')}`, phone: `09000000${String(i + 1).padStart(2, '0')}`, occupancy_status: ['ACTIVE', 'MOVED_OUT', 'UNASSIGNED'][i % 3], current_residence: i % 3 ? null : { boarding_house_id: 3, boarding_house_name: 'Nhà thử', room_id: 11, room_code: '101' } }))
const server = await createServer({ root: resolve(root, 'front-end'), configFile: resolve(root, 'front-end/vite.config.js'), define: { 'import.meta.env.VITE_API_BASE_URL': JSON.stringify('/api') }, plugins: [{ name: 'tenant-picker-audit', configureServer(vite) {
  vite.middlewares.use('/tenant-picker-audit', async (_request, response) => {
    response.setHeader('Content-Type', 'text/html')
    response.end(await vite.transformIndexHtml('/tenant-picker-audit', '<html lang="vi"><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/tests/tenant-picker-audit.jsx"></script></body></html>'))
  })
} }], server: { host: '127.0.0.1', port: 18948, strictPort: true } })
let browser
try {
  await mkdir(output, { recursive: true })
  await server.listen()
  browser = await chromium.launch({ executablePath: process.env.E2E_CHROMIUM_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage({ viewport: { width: 1200, height: 900 } })
  const errors = [], lookups = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*', async route => {
    const request = route.request(), url = new URL(request.url())
    assert.equal(url.origin, origin, 'Only isolated local fixture requests')
    if (!url.pathname.startsWith('/api/')) return route.continue()
    assert.equal(request.method(), 'GET', 'Forms submit to fixture callback only')
    const ok = data => route.fulfill({ json: { success: true, data } })
    if (url.pathname.endsWith('/tenant-lookup/options')) return ok({ houses: [{ id: 3, name: 'Nhà thử' }], rooms: [{ id: 11, room_code: '101' }], can_create: true })
    if (url.pathname.endsWith('/beds')) return ok([{ id: 1, bed_code: 'G01', status: 'AVAILABLE' }])
    assert.equal(url.pathname, '/api/tenant-lookup', 'Never load all tenants endpoint')
    const q = url.searchParams
    lookups.push({ search: q.get('search'), page: Number(q.get('page') || 1), scope: q.get('scope'), context: q.get('context_room_id') })
    if (q.get('search') === 'loi') return route.fulfill({ status: 500, json: { success: false, message: 'Lỗi kiểm thử' } })
    if (q.get('search') === 'cham') await new Promise(resolve => setTimeout(resolve, 700))
    let rows = tenants
    if (q.get('scope') === 'ACTIVE_ROOM') rows = rows.filter(tenant => [1, 2].includes(tenant.id))
    const ids = q.getAll('ids[]').map(Number), exclude = q.getAll('exclude_ids[]').map(Number)
    if (ids.length) rows = rows.filter(tenant => ids.includes(tenant.id))
    rows = rows.filter(tenant => !exclude.includes(tenant.id))
    if (q.get('search')) rows = rows.filter(tenant => `${tenant.full_name} ${tenant.phone}`.toLowerCase().includes(q.get('search').toLowerCase()))
    if (q.get('occupancy_status')) rows = rows.filter(tenant => tenant.occupancy_status === q.get('occupancy_status'))
    if (q.get('room_id') || q.get('boarding_house_id')) rows = rows.filter(tenant => tenant.current_residence)
    const size = Number(q.get('per_page') || 20), current = Number(q.get('page') || 1)
    return ok({ tenants: rows.slice((current - 1) * size, current * size), total: rows.length, current_page: current, last_page: Math.max(1, Math.ceil(rows.length / size)), per_page: size, can_search_identity: true })
  })
  const visit = query => page.goto(`${origin}/tenant-picker-audit?${query}`)
  const dialog = page.getByRole('dialog', { name: 'Chọn người thuê', exact: true })
  const open = async label => { await page.getByRole('button', { name: label, exact: true }).click(); await dialog.getByRole('radio').or(dialog.getByRole('checkbox')).first().waitFor() }
  const pick = async (name, multiple = false) => dialog.getByRole(multiple ? 'checkbox' : 'radio', { name: new RegExp(name) }).check()
  const confirm = () => dialog.getByRole('button', { name: 'Xác nhận chọn', exact: true }).click()
  await visit('mode=multi')
  await open('Người ở cùng')
  assert.equal(lookups.length, 1, 'One initial list request')
  assert.equal(await dialog.getByRole('checkbox').count(), 20)
  await pick('Người thử 01', true)
  await dialog.getByRole('button', { name: 'Sau', exact: true }).click()
  await pick('Người thử 21', true)
  await dialog.getByRole('button', { name: 'Trước', exact: true }).click()
  assert.equal(await dialog.getByRole('checkbox', { name: /Người thử 01/ }).isChecked(), true)
  await confirm()
  assert.deepEqual(JSON.parse(await page.locator('#selected').innerText()), [1, 21])
  await open('Người ở cùng')
  await dialog.getByRole('checkbox', { name: /Người thử 01/ }).uncheck()
  await dialog.getByRole('button', { name: 'Hủy', exact: true }).click()
  assert.deepEqual(JSON.parse(await page.locator('#selected').innerText()), [1, 21])
  await open('Người ở cùng')
  const before = lookups.length
  await dialog.getByRole('searchbox').pressSequentially('Người thử 45', { delay: 20 })
  await dialog.getByText('Người thử 45', { exact: true }).waitFor()
  assert.equal(lookups.length - before, 1, 'Debounced typing produces one request')
  await dialog.getByRole('searchbox').fill('0900000044')
  await dialog.getByText('Người thử 44', { exact: true }).waitFor()
  await dialog.getByRole('searchbox').fill('cham')
  await page.waitForTimeout(350)
  await dialog.getByRole('searchbox').fill('Người thử 43')
  await dialog.getByText('Người thử 43', { exact: true }).waitFor()
  await page.waitForTimeout(800)
  assert.equal(await dialog.getByText('Người thử 43', { exact: true }).count(), 1, 'Old response never replaces latest search')
  await dialog.getByRole('searchbox').fill('')
  await dialog.getByLabel('Trạng thái cư trú').selectOption('MOVED_OUT')
  await page.waitForTimeout(400)
  assert.equal(await dialog.getByRole('checkbox').count(), 15)
  await dialog.getByLabel('Trạng thái cư trú').selectOption('')
  await dialog.getByLabel('Nhà trọ', { exact: true }).selectOption('3')
  await dialog.getByLabel('Phòng', { exact: true }).selectOption('11')
  await dialog.getByRole('checkbox').first().waitFor()
  assert.equal(await dialog.getByRole('checkbox').count(), 15)
  await dialog.getByRole('searchbox').fill('loi')
  await dialog.getByRole('button', { name: 'Thử lại', exact: true }).waitFor()
  const toast = page.getByLabel('Thông báo')
  await toast.getByText('Không thành công', { exact: true }).waitFor()
  assert.equal(await toast.getByText('Không thành công', { exact: true }).count(), 1)
  await dialog.getByRole('searchbox').fill('khong-co')
  await dialog.getByText('Không tìm thấy người thuê phù hợp.', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  assert.equal(await dialog.count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Người ở cùng', exact: true }).evaluate(node => document.activeElement === node), true)

  for (const dorm of [false, true]) {
    await visit(`mode=contract${dorm ? '&dorm=1' : ''}`)
    await open('Người đứng tên')
    await pick('Người thử 03')
    await confirm()
    await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
    await open('Người ở cùng')
    assert.equal(await dialog.getByText('Người thử 03', { exact: true }).count(), 0, 'Primary excluded from roommates')
    await pick('Người thử 04', true)
    await confirm()
    await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
    await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click()
    await page.getByRole('button', { name: 'Lưu nháp', exact: true }).click()
    const result = JSON.parse(await page.locator('#result').innerText())
    assert.equal(result.tenant_id, 3)
    assert.deepEqual(result.occupant_tenant_ids, [4])
    assert.equal(result.contract_type, dorm ? 'DORM_BED' : 'ROOM_RENTAL')
  }
  for (const dorm of [false, true]) {
    await visit(`mode=room${dorm ? '&dorm=1' : ''}`)
    await open('Người thuê'); await pick('Người thử 05'); await confirm()
    await page.getByRole('button', { name: 'Lưu người ở', exact: true }).click()
    assert.equal(JSON.parse(await page.locator('#result').innerText()).tenant_id, 5)
  }
  await visit('mode=residence')
  await open('Chọn người kê khai')
  assert.equal(await dialog.getByRole('radio').count(), 2)
  assert.equal(lookups.at(-1).scope, 'ACTIVE_ROOM')
  assert.equal(lookups.at(-1).context, '11')
  assert.equal(await dialog.getByLabel('Nhà trọ', { exact: true }).count(), 0)
  await pick('Người thử 01'); await confirm()
  await open('Thành viên cùng thay đổi'); await pick('Người thử 02', true); await confirm()
  await page.getByRole('button', { name: 'Lưu bản nháp', exact: true }).click()
  const residence = JSON.parse(await page.locator('#result').innerText())
  assert.equal(residence.declarant_tenant_id, 1)
  assert.deepEqual(residence.members.map(member => member.tenant_id), [2])

  await page.setViewportSize({ width: 390, height: 844 })
  await visit('mode=multi')
  await open('Người ở cùng')
  const box = await dialog.boundingBox(), button = await dialog.getByRole('button', { name: 'Xác nhận chọn', exact: true }).boundingBox()
  assert.ok(box.x >= 0 && box.x + box.width <= 390)
  assert.ok(button.y >= 0 && button.y + button.height <= 844)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await dialog.getByRole('button', { name: 'Xác nhận chọn', exact: true }).focus()
  await page.keyboard.press('Tab')
  assert.equal(await dialog.getByRole('button', { name: 'Đóng chọn người thuê', exact: true }).evaluate(node => node === document.activeElement), true, 'Focus wraps inside dialog')
  await page.screenshot({ path: resolve(output, 'mobile.png') })
  await page.keyboard.press('Escape')
  await open('Người ở cùng')
  await page.mouse.click(1, 1)
  assert.equal(await dialog.count(), 0, 'Backdrop closes without committing')
  assert.deepEqual(errors, [])
  console.log('Passed: pagination, debounce, stale-response cancellation, filters, multi/cancel, Toast/error, room/KTX contract and occupant payloads, CT01 scope, mobile, keyboard/focus/backdrop; no all-tenant request.')
} finally {
  await browser?.close()
  await server.close()
}
