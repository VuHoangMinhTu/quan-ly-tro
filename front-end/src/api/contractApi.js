import client from './axiosClient'
export const getContractsByRoom = (roomId) => client.get(`/rooms/${roomId}/contracts`)
export const getContract = (id) => client.get(`/contracts/${id}`)
export const getHandoverCheckIn = id => client.get(`/contracts/${id}/handover-check-in`)
export const createHandoverCheckIn = id => client.post(`/contracts/${id}/handover-check-in`)
export const updateHandoverCheckIn = (id, items) => client.put(`/contracts/${id}/handover-check-in`, { items })
export const confirmHandoverCheckIn = id => client.post(`/contracts/${id}/handover-check-in/confirm`)
export const createContract = (roomId, payload) => client.post(`/rooms/${roomId}/contracts`, payload)
export const updateContract = (id, payload) => client.put(`/contracts/${id}`, payload)
export const deleteContract = (id) => client.delete(`/contracts/${id}`)
export const getContractContext = (roomId) => client.get(`/rooms/${roomId}/contract-context`)
export const createBed = (roomId, payload) => client.post(`/rooms/${roomId}/beds`, payload)
export const updateContractStatus = (id, payload) => client.put(`/contracts/${id}/status`, payload)
export const changeContractRoom = (id, roomId) => client.put(`/contracts/${id}/room`, { room_id: roomId })
export const moveOutContractOccupant = (id, occupantId, payload) => client.put(`/contracts/${id}/occupants/${occupantId}/move-out`, payload)
export const updateContractSchedule = (houseId, payload) => client.put(`/boarding-houses/${houseId}/contract-schedule`, payload)
export const getContractServices = id => client.get(`/contracts/${id}/services`)
export const saveContractServices = (id, payload) => client.put(`/contracts/${id}/services`, payload)
export const adjustContractService = (id, payload) => client.post(`/contracts/${id}/service-adjustments`, payload)
export const stopContractService = (id, termId, payload) => client.post(`/contracts/${id}/services/${termId}/stop`, payload)
